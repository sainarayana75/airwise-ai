// ==============================================================
// DAILY ROUTINE GENERATOR
// Context-aware routine recommendations adapting to live AQI & family profile
// ==============================================================

import {
  AirQualityData,
  DailyRoutinePlan,
  RoutineRecommendation,
  UserProfile,
} from '../types';
import { calculateCommuteEmissions } from '../utils/emission-calculator';

/**
 * Generate intelligent, context-aware daily routine recommendations
 * strictly adapting to live environmental conditions + user family profile
 */
export function generateDailyPlan(
  user: UserProfile,
  envData: AirQualityData
): DailyRoutinePlan {
  const { aqi, pollutants, weather } = envData;
  const isSevere = aqi > 200;
  const isUnhealthy = aqi > 150;
  const isModerateOrHigher = aqi > 100;
  const isFreezing = weather.temperature < 8;

  // Detect if household has high-risk vulnerable members
  const hasVulnerable = user.familyMembers.some(
    m => m.ageGroup === 'infant' || m.ageGroup === 'child' || m.ageGroup === 'elderly' || m.hasRespiratoryCondition || m.isPregnant
  );
  const hasAsthma = user.familyMembers.some(m => m.hasRespiratoryCondition);

  // Overall exposure risk classification
  let overallRisk: 'Low' | 'Moderate' | 'High' | 'Severe' = 'Low';
  if (aqi > 250) overallRisk = 'Severe';
  else if (aqi > 150) overallRisk = 'High';
  else if (aqi > 75) overallRisk = 'Moderate';

  const morningRecs: RoutineRecommendation[] = [];
  const afternoonRecs: RoutineRecommendation[] = [];
  const eveningRecs: RoutineRecommendation[] = [];

  // ==========================================
  // MORNING RECOMMENDATIONS
  // ==========================================
  if (user.outdoorActivityPreference === 'morning_runs' || user.outdoorActivityPreference === 'weekend_sports') {
    if (isModerateOrHigher) {
      morningRecs.push({
        id: 'rec-morn-indoor-exercise',
        timeOfDay: 'morning',
        title: 'Shift Morning Cardio to Indoor Session',
        suggestedAction: 'Substitute outdoor running or jogging with indoor bodyweight circuits, yoga, or treadmill workouts in a filtered room.',
        reason: `Current outdoor AQI is ${aqi} (${envData.category}), with PM2.5 at ${pollutants.pm2_5 ?? 'elevated'} µg/m³. Deep inhalation during outdoor aerobic exercise increases particulate lung deposition by 4-6x.`,
        pollutionConsideration: 'Early morning thermal inversions frequently trap vehicular and industrial particulates at ground level until solar heating breaks the boundary layer.',
        personalBenefit: 'Averts acute airway inflammation, bronchiolar constriction, and oxidative cardiovascular stress.',
        environmentalBenefit: 'Zero emissions generated by exercising at home.',
        estimatedImpact: 'Reduces inhaled fine particulate burden by ~85% compared to outdoor running.',
        assumptions: 'Calculated assuming ~30-45 minutes aerobic breathing rate of 50-70 L/min vs resting indoor breathing rate.',
        category: 'outdoor_activity',
        priority: isSevere ? 'critical' : 'high',
        completed: false,
        isIndoorAlternative: true,
      });
    } else {
      morningRecs.push({
        id: 'rec-morn-outdoor-run-safe',
        timeOfDay: 'morning',
        title: 'Outdoor Exercise is Safe This Morning',
        suggestedAction: 'Enjoy your outdoor run or morning walk; conditions are favorable.',
        reason: `Outdoor AQI is ${aqi} (${envData.category}), which meets safe health standards for general physical activity.`,
        pollutionConsideration: 'Clean atmospheric boundary layer and adequate wind dispersion keep particulates low.',
        personalBenefit: 'Boosts cardiovascular health, endorphins, and vitamin D synthesis.',
        environmentalBenefit: 'Zero transport emissions.',
        estimatedImpact: 'Optimal aerobic workout with minimal ambient pollution exposure.',
        assumptions: 'Based on current clean air quality reading below health warning thresholds.',
        category: 'outdoor_activity',
        priority: 'info',
        completed: false,
        isIndoorAlternative: false,
      });
    }
  }

  // Commute Recommendation
  if (user.workSchedule !== 'remote') {
    if (user.primaryCommuteMode === 'car_petrol' || user.primaryCommuteMode === 'car_diesel') {
      const impact = calculateCommuteEmissions(user.dailyCommuteDistanceKm, 'bus', user.primaryCommuteMode);
      morningRecs.push({
        id: 'rec-morn-commute-transit',
        timeOfDay: 'morning',
        title: 'Adopt Public Transit or Carpooling for Commute',
        suggestedAction: `Switch today's ${user.dailyCommuteDistanceKm} km solo drive to public transit (metro/bus) or arrange a carpool.`,
        reason: `Personal vehicle traffic contributes substantially to urban morning smog peaks and NOx emissions.`,
        pollutionConsideration: `Roadway corridors have localized PM2.5 concentrations up to 3x higher than ambient city background levels.`,
        personalBenefit: isSevere 
          ? 'Modern electric metros and filtered transit buses reduce exposure compared to sitting in slow bumper-to-bumper car traffic with open vents.'
          : 'Reduces driving stress and lowers fuel expenditure.',
        environmentalBenefit: `Avoids approximately ${impact.avoidedCo2Kg} kg of CO2 emissions for today's trip.`,
        estimatedImpact: `${impact.percentageReduced}% carbon reduction for today's commute.`,
        assumptions: impact.assumptions,
        category: 'commute',
        priority: isSevere ? 'high' : 'medium',
        completed: false,
        isIndoorAlternative: false,
      });
    } else if (user.primaryCommuteMode === 'bicycle' || user.primaryCommuteMode === 'walking') {
      if (isUnhealthy) {
        morningRecs.push({
          id: 'rec-morn-commute-safety-warning',
          timeOfDay: 'morning',
          title: 'Pause Active Commuting Today — Take Transit or Rideshare',
          suggestedAction: 'Avoid cycling or walking long distances alongside traffic today. Take an enclosed bus, train, or rideshare with an N95 mask.',
          reason: `Although walking/biking is zero-carbon, doing heavy aerobic commuting in AQI ${aqi} poses severe respiratory health risks.`,
          pollutionConsideration: 'Inhaling elevated PM2.5 under exertion counteracts the health benefits of cardiovascular exercise.',
          personalBenefit: 'Shields respiratory tract and lungs from dangerous fine particulate spikes.',
          environmentalBenefit: 'Public transit remains highly sustainable while protecting your lungs.',
          estimatedImpact: 'Prevents acute toxic aerosol inhalation during peak morning rush hour.',
          assumptions: 'Health safety strictly supersedes personal zero-emission goals during smog emergencies.',
          category: 'commute',
          priority: 'critical',
          completed: false,
          isIndoorAlternative: true,
        });
      }
    }
  }

  // Vulnerable household morning protection
  if (hasVulnerable && isModerateOrHigher) {
    morningRecs.push({
      id: 'rec-morn-vulnerable-protection',
      timeOfDay: 'morning',
      title: 'Protect Sensitive Family Members During Morning Rush',
      suggestedAction: hasAsthma 
        ? 'Ensure asthma inhalers are on hand; pre-filter children’s and elderly bedrooms with HEPA or clean-air fans.'
        : 'Keep children and elderly indoors; avoid morning balcony or playground time until afternoon.',
      reason: 'Young lungs have higher breathing-rate-to-body-mass ratios and elderly cardiovascular systems are vulnerable to PM2.5 spikes.',
      pollutionConsideration: 'Vehicular exhaust peaks between 7:30 AM and 9:30 AM.',
      personalBenefit: 'Prevents asthma triggers, coughing, wheezing, and irritation.',
      environmentalBenefit: 'Protective health measure.',
      estimatedImpact: 'Reduces sensitive member particulate intake by over 70%.',
      assumptions: 'Based on pediatric environmental health exposure models.',
      category: 'health_protection',
      priority: 'critical',
      completed: false,
      isIndoorAlternative: true,
    });
  }

  // ==========================================
  // AFTERNOON RECOMMENDATIONS
  // ==========================================
  // Ventilation recommendation
  if (isSevere) {
    afternoonRecs.push({
      id: 'rec-aft-keep-windows-sealed',
      timeOfDay: 'afternoon',
      title: 'Maintain Sealed Indoor Envelope & Window Closures',
      suggestedAction: 'Keep all exterior windows and doors firmly shut. Use draft stoppers or rolled damp towels under door gaps if air purifiers are running.',
      reason: `Outdoor AQI is ${aqi}. Natural ventilation would introduce dangerous PM2.5 concentrations directly into your living space.`,
      pollutionConsideration: 'Ambient particulate levels remain above safe indoor thresholds throughout the day.',
      personalBenefit: 'Maintains low indoor particle counts and allows purifiers to achieve effective clean air delivery.',
      environmentalBenefit: 'Prevents purifiers from over-consuming energy trying to clean continuous infiltration.',
      estimatedImpact: 'Keeps indoor PM2.5 at least 50-70% lower than outdoor ambient air.',
      assumptions: 'Standard residential envelope infiltration rate of 0.5 air changes per hour.',
      category: 'indoor_ventilation',
      priority: 'high',
      completed: false,
      isIndoorAlternative: false,
    });
  } else if (aqi <= 65) {
    afternoonRecs.push({
      id: 'rec-aft-open-windows-airing',
      timeOfDay: 'afternoon',
      title: 'Optimal Window Ventilation Opportunity',
      suggestedAction: 'Open windows on opposite sides of your home for 15-20 minutes to cross-ventilate and purge accumulated indoor CO2.',
      reason: `Outdoor air quality is currently favorable (${aqi} AQI), making this an optimal window for natural ventilation.`,
      pollutionConsideration: 'Solar heating and daytime wind dispersion have cleared lingering morning pollutants.',
      personalBenefit: 'Flushes indoor stale carbon dioxide, cooking VOCs, and moisture without introducing smog.',
      environmentalBenefit: 'Natural cooling and ventilation reduces air conditioning and mechanical fan energy.',
      estimatedImpact: 'Reduces indoor CO2 concentration from ~1200 ppm to ambient ~450 ppm.',
      assumptions: '15-minute cross-ventilation provides 2-3 complete room air changes.',
      category: 'indoor_ventilation',
      priority: 'medium',
      completed: false,
      isIndoorAlternative: false,
    });
  } else {
    afternoonRecs.push({
      id: 'rec-aft-moderate-ventilation',
      timeOfDay: 'afternoon',
      title: 'Selective Mid-Afternoon Window Airing',
      suggestedAction: 'If indoor air feels stuffy, open windows briefly (10-15 mins) during peak afternoon warmth (2 PM - 3:30 PM), then seal and resume air purification.',
      reason: 'Thermal convection tends to produce the lowest particulate density of the daylight hours around 2-4 PM.',
      pollutionConsideration: 'Avoid opening windows facing busy roadways.',
      personalBenefit: 'Balances indoor CO2 reduction with particulate protection.',
      environmentalBenefit: 'Zero-power natural air exchange.',
      estimatedImpact: 'Refreshes room air with minimal particulate infiltration if kept brief.',
      assumptions: 'Brief ventilation window followed by 20 minutes of HEPA recirculation.',
      category: 'indoor_ventilation',
      priority: 'medium',
      completed: false,
      isIndoorAlternative: false,
    });
  }

  // Cooking and indoor source control
  afternoonRecs.push({
    id: 'rec-aft-cooking-hygiene',
    timeOfDay: 'afternoon',
    title: 'Low-Emission Kitchen Practices',
    suggestedAction: user.hasKitchenExhaust
      ? 'Turn on the kitchen range exhaust on high before lighting the stove and keep it running 10 minutes post-cooking.'
      : 'Cover pans with lids while cooking, avoid high-heat deep frying or searing, and isolate the kitchen from sleeping areas.',
    reason: 'Indoor frying, roasting, and gas combustion generate extreme PM2.5 and nitrogen dioxide (NO2) spikes exceeding 300 µg/m³ in confined rooms.',
    pollutionConsideration: 'When outdoor smog prevents opening windows, indoor-generated cooking emissions linger for hours.',
    personalBenefit: 'Protects family members from acute indoor pollutant spikes that trigger asthma and respiratory irritation.',
    environmentalBenefit: 'Lid-covered cooking reduces energy consumption by 20-30%.',
    estimatedImpact: 'Prevents kitchen-generated PM2.5 from dispersing throughout the rest of the home.',
    assumptions: 'Cooking produces 15-40 mg of fine aerosols per meal if unmitigated.',
    category: 'health_protection',
    priority: 'high',
    completed: false,
    isIndoorAlternative: false,
  });

  // ==========================================
  // EVENING RECOMMENDATIONS
  // ==========================================
  // Dust & floor maintenance
  eveningRecs.push({
    id: 'rec-eve-damp-mopping',
    timeOfDay: 'evening',
    title: 'Damp Mop Floors Instead of Dry Brooming',
    suggestedAction: 'Use a damp microfiber mop or cloth on hard floors; avoid dry sweeping or feather dusters.',
    reason: 'Dry brooms re-suspend settled fine particulates and heavy dust into the breathing zone for 2-4 hours.',
    pollutionConsideration: 'Settled PM10 and heavy PM2.5 particles are easily kicked back into the air by footsteps.',
    personalBenefit: 'Creates a clean allergen-free breathing environment for night sleep.',
    environmentalBenefit: 'Zero chemical aerosols; minimal water usage.',
    estimatedImpact: 'Cuts overnight resuspension of settled dust by up to 80%.',
    assumptions: 'Damp cleaning traps particles through surface tension.',
    category: 'health_protection',
    priority: 'medium',
    completed: false,
    isIndoorAlternative: false,
  });

  // Sleeping room air preparation
  if (user.hasAirPurifier) {
    eveningRecs.push({
      id: 'rec-eve-hepa-bedroom',
      timeOfDay: 'evening',
      title: 'Pre-Filter Sleeping Bedrooms 1 Hour Before Bed',
      suggestedAction: 'Close bedroom doors and run the HEPA air purifier on high speed for 45 minutes, then switch to quiet night mode.',
      reason: 'Humans spend 7-9 continuous hours sleeping in one room. Overnight nocturnal smog inversions peak between 11 PM and 5 AM.',
      pollutionConsideration: 'Nighttime temperature drops compress pollution into a shallow boundary layer.',
      personalBenefit: 'Provides restorative sleep with near-zero particulate lung irritation.',
      environmentalBenefit: 'Targeted bedroom filtration uses 60% less electricity than attempting to filter the entire house overnight.',
      estimatedImpact: 'Reduces bedroom PM2.5 below 10 µg/m³ during sleep.',
      assumptions: 'Standard bedroom volume of 35-50 m³ with CADR > 120 m³/h.',
      category: 'indoor_ventilation',
      priority: isSevere ? 'critical' : 'high',
      completed: false,
      isIndoorAlternative: false,
    });
  } else {
    // Budget-friendly alternative for non-purifier homes
    eveningRecs.push({
      id: 'rec-eve-clean-room-setup',
      timeOfDay: 'evening',
      title: 'Designate a Sealed Clean-Air Sleeping Zone',
      suggestedAction: 'Seal bedroom window cracks with weatherstripping or painter tape, run a basic box fan with MERV filter or avoid drafty door gaps.',
      reason: user.budget === 'low' 
        ? 'Affordable, DIY clean-room isolation drastically drops night particulate exposure without expensive electronics.'
        : 'Concentrating clean air efforts in the bedroom yields maximum daily health return.',
      pollutionConsideration: 'Outdoor overnight smog easily infiltrates leaky single-pane window frames.',
      personalBenefit: 'Protects cardiovascular recovery during nocturnal hours.',
      environmentalBenefit: 'Zero high-wattage equipment required.',
      estimatedImpact: 'Cuts infiltration rates by 40-50%.',
      assumptions: 'Sealing cracks prevents exterior air draft infiltration.',
      category: 'indoor_ventilation',
      priority: 'high',
      completed: false,
      isIndoorAlternative: true,
    });
  }

  // Energy-saving sustainable routine
  eveningRecs.push({
    id: 'rec-eve-energy-conservation',
    timeOfDay: 'evening',
    title: isFreezing ? 'Targeted Space Heating & Draft Elimination' : 'Smart Heating & Energy Conservation Habit',
    suggestedAction: isFreezing
      ? `Outdoor temperature is ${weather.temperature}°C with ${weather.weatherDescription}. Heat only occupied bedrooms rather than central full-home heating.`
      : 'Adjust winter space heater or thermostat by 1°C lower and wear layered clothing; ensure heater filters are clean.',
    reason: 'Power generation during winter peak heating drives elevated regional fossil fuel emissions and coal/gas power plant plumes.',
    pollutionConsideration: 'Grid electricity demand is highest during cold winter evenings.',
    personalBenefit: 'Saves 5-10% on monthly heating utility bills while preventing dry mucosal irritation.',
    environmentalBenefit: 'Avoids ~1.1 kg of CO2 emissions per household day.',
    estimatedImpact: 'Direct 7% reduction in daily heating carbon footprint.',
    assumptions: 'Based on US Department of Energy winter thermostat efficiency calculations.',
    category: 'energy_conservation',
    priority: 'medium',
    completed: false,
    isIndoorAlternative: false,
  });

  const planSummary = isSevere
    ? `Severe smog alert (${aqi} AQI). Outdoor physical exertion is suspended; prioritize indoor air filtering and transit.`
    : isUnhealthy
    ? `Unhealthy air quality today (${aqi} AQI). Shift workouts indoors and protect vulnerable family members.`
    : isModerateOrHigher
    ? `Moderate air conditions (${aqi} AQI). Sensitive individuals should take precautions; active commute with care.`
    : `Clean air conditions (${aqi} AQI). Ideal day for outdoor activities, natural ventilation, and low-emission active commuting.`;

  return {
    date: new Date().toLocaleDateString('en-US', { weekday: 'long', month: 'long', day: 'numeric' }),
    summary: planSummary,
    overallExposureRisk: overallRisk,
    morning: morningRecs,
    afternoon: afternoonRecs,
    evening: eveningRecs,
  };
}
